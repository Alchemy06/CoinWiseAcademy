function resolveDynamicTranslation(locale: Locale, source: string): string | null {
  // A few strings are assembled at runtime, so capture those shapes here instead of exploding the static dictionary.
  if (locale !== "zh-CN") {
    return null;
  }

  let match = source.match(/^Updated\s+(.+)$/);
  if (match) {
    return `已更新 ${match[1]}`;
  }

  match = source.match(/^Learn progress (\d+) of (\d+), (\d+)% complete$/);
  if (match) {
    return `学习进度 ${match[1]}/${match[2]}，已完成 ${match[3]}%`;
  }

  match = source.match(/^Quiz progress (\d+) of (\d+), (\d+)% complete$/);
  if (match) {
    return `测验进度 ${match[1]}/${match[2]}，已完成 ${match[3]}%`;
  }

  match = source.match(/^User avatar for\s+(.+)$/);
  if (match) {
    return `${match[1]} 的用户头像`;
  }

  return null;
}

function normalizeTranslationKey(source: string): string {
  // Collapse incidental JSX whitespace so formatting-only edits do not create duplicate translation keys.
  return source.replace(/\s+/g, " ").trim();
}

export function translateLoose(locale: Locale, source: string): string {
  // Try exact, normalized, and dynamic matches in order, then fall back to the source copy unchanged.
  const exact = locale === "zh-CN" ? MESSAGES["zh-CN"][source] : undefined;
  if (typeof exact === "string") {
    return exact;
  }

  if (locale === "zh-CN") {
    const normalizedSource = normalizeTranslationKey(source);
    const normalizedExact = MESSAGES["zh-CN"][normalizedSource];
    if (typeof normalizedExact === "string") {
      return normalizedExact;
    }
  }

  return resolveDynamicTranslation(locale, source) ?? source;
}

export function translate(locale: Locale, source: string, params?: TranslationParams): string {
  // Interpolate after lookup so translated templates can reuse the same placeholder keys as the source copy.
  const template = translateLoose(locale, source);
  if (!params) {
    return template;
  }

  return template.replace(/\{(\w+)\}/g, (_, key: string) => String(params[key] ?? `{${key}}`));
}
